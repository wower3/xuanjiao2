-- 验证结果
SELECT
    r.name AS '角色',
    COUNT(rm.menu_id) AS '菜单数量'
FROM sys_role r
LEFT JOIN sys_role_menu rm ON r.id = rm.role_id
GROUP BY r.id, r.name
ORDER BY r.id;

SELECT '菜单权限修复完成！' AS '状态';
